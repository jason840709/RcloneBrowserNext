export type Translate = (key: Key) => string;
export function resolveLanguage(value: string): ResolvedLanguage {
  const primary = value.toLowerCase().split(/[-_]/)[0];
  return primary === 'zh' ? 'zh-TW' : primary === 'ja' ? 'ja' : 'en';
}

export function translator(language: Language): Translate {
  const resolved = language === 'system' ? resolveLanguage(navigator.languages?.[0] || navigator.language || 'en') : language;
  return key => (resolved === 'en' ? en : resolved === 'ja' ? ja : zh)[key];
}
